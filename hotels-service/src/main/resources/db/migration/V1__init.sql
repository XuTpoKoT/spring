CREATE TABLE hotels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(512) NOT NULL,
    CONSTRAINT uk_hotels_name UNIQUE (name)
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id BIGINT NOT NULL,
    number VARCHAR(32) NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    times_booked INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_rooms_hotel FOREIGN KEY (hotel_id) REFERENCES hotels (id),
    CONSTRAINT uk_rooms_hotel_number UNIQUE (hotel_id, number),
    CONSTRAINT ck_rooms_times_booked CHECK (times_booked >= 0)
);

CREATE TABLE room_locks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    booking_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    request_id VARCHAR(64),
    CONSTRAINT fk_room_locks_room FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT uk_room_locks_booking UNIQUE (room_id, booking_id),
    CONSTRAINT uk_room_locks_request UNIQUE (request_id),
    CONSTRAINT ck_room_locks_dates CHECK (end_date > start_date)
);

CREATE INDEX idx_room_locks_room_dates ON room_locks (room_id, start_date, end_date);
CREATE INDEX idx_rooms_hotel_id ON rooms (hotel_id);
